"""Generate the schema-v1 diagnostic candidate from the T-1.2 layout.

Pressure steps use the M-1 band method. G-CYCLE consumes sequential phases.
The time-domain X-1 calculation accounts for concurrent returns and recharge.
"""
from math import fsum

import yaml

from geometry import DUMP_TIMES_S, ROOT, calculate, read_yaml
from x1_calc import Accumulator, IDLE_KW, M3_S_TO_L_MIN, MOTOR_KW, PUMP_ETA, make_model, motions

BAND_UPPER_BAR = (20, 50, 100, 150, 200, 250, float("inf"))
SAMPLES = 4000
DUMP_S = max(DUMP_TIMES_S)


def motion_rows(motion, drive):
    groups = []
    speed_mm_s = motion.speed_m_s * 1000
    target_flow_L_min = motion.speed_m_s * motion.flow_area_m2 * M3_S_TO_L_MIN
    accumulator = motion.name == "return"
    for index in range(SAMPLES):
        start_m = motion.stroke_m * index / SAMPLES
        end_m = motion.stroke_m * (index + 1) / SAMPLES
        pressure_bar = max(motion.pressure_bar(start_m), motion.pressure_bar(end_m))
        flow_L_min = min(drive["pump_max_flow_L_min"], 600 * drive["motor_kW"] * drive["eta"] / pressure_bar)
        speed = speed_mm_s if accumulator or target_flow_L_min <= flow_L_min else "pump"
        band = next(edge for edge in BAND_UPPER_BAR if pressure_bar <= edge)
        if groups and groups[-1][0:2] == [band, speed]:
            groups[-1][2] = end_m
            groups[-1][3] = max(pressure_bar, groups[-1][3])
        else:
            groups.append([band, speed, end_m, pressure_bar])
    rows = []
    for _, speed, end_m, pressure_bar in groups:
        stroke_mm = end_m * 1000 - fsum(r["stroke_mm"] for r in rows)
        row = {"name": f"{motion.name} {len(rows) + 1}", "actuator": motion.actuator,
               "stroke_mm": stroke_mm, "direction": "retract" if motion.mode == "retract" else "extend",
               "pressure_bar": pressure_bar, "speed_mm_s": speed, "regeneration": motion.mode == "regen",
               "dwell_s": 0}
        if rows:
            row["continues"] = True
        if accumulator:
            row["use_accumulator"] = True
        rows.append(row)
    return rows


def main():
    material, results = calculate()
    params = read_yaml("design/params.m1.yaml")
    axis, pre = results["axis"], results["precompaction"]
    base = next(r for r in results["briquettes"] if (r["case"], r["pressure_basis"]) == ("base", "nominal_force"))
    model, cylinder = make_model(material, results, base, params)
    status = "candidate" if results["selection"]["base_cycle_limit_pass"] else "diagnostic candidate"
    params["description"] = (
        f"T-1.2 D0 {status}, axial window {axis['transferred_fill_length_mm']} mm. "
        f"Sequential nominal-dose cycle with {DUMP_S:.2f} s dump.")

    params["product"]["density_kg_m3"] = base["released_density_kg_m3"]
    params["main_cylinder"].update(stroke_mm=axis["main_installed_stroke_mm"],
                                   working_range_mm=axis["main_required_travel_mm"])
    chamber = params["chamber"]
    chamber.pop("ejection_stroke_mm", None)
    chamber.update(length_mm=axis["body_length_mm"], approach_stroke_mm=axis["approach_stroke_mm"],
                   ejection_overtravel_mm=axis["ejection_overtravel_mm"],
                   in_die_density_kg_m3=base["in_die_density_kg_m3"])
    params["precompaction"].update(
        section_mm=pre["window_mm_axial_transverse"], loose_fill_length_mm=pre["fill_height_mm"],
        stroke_mm=pre["stroke_mm"], post_precompaction_density_kg_m3=pre["post_precompaction_density_kg_m3"],
        cylinder={"n": 1, "bore_mm": pre["bore_mm"], "rod_mm": pre["rod_mm"],
                  "stroke_mm": pre["cylinder_stroke_mm"], "eta": pre["cylinder_eta"]})
    drive = params["drive"]
    drive["eta"] = PUMP_ETA * (MOTOR_KW - IDLE_KW) / MOTOR_KW
    drive["slide_gate_cylinder"]["eta"] = model.gate_cylinder.eta
    charge = Accumulator()
    drive["accumulator"] = {
        "usable_oil_L": 1000 * (charge.oil_at_m3(charge.high_bar) - charge.oil_at_m3(charge.low_bar)),
        "max_flow_L_min": charge.delivery_L_min, "min_delivery_pressure_bar": charge.low_bar,
        "charge_pressure_bar": charge.high_bar + 3, "round_trip_eta": 1.0,
    }
    phase_rows = []
    for name, motion in motions(model, cylinder, base["bulk_density_kg_m3"]).items():
        rows = motion_rows(motion, drive)
        if name == "press":
            rows[-1].update(press=True, dwell_s=0.55)  # X-1 hold, unload and their switches.
        if name == "pre_up":
            rows[-1]["dwell_s"] = DUMP_S
        phase_rows.extend(rows)
    params["cycle"] = phase_rows

    (ROOT / "design/params.t12.yaml").write_text(
        "# T-1.2 generated by calc/T-1.2/make_params_t12.py.\n"
        "# The schema models return motions and accumulator recharge sequentially.\n"
        "# See calc/T-1.2/results.json for the concurrent hydraulic calculation.\n"
        + yaml.safe_dump(params, allow_unicode=True, sort_keys=False), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
